// node build.mjs: s-web.js, one classic script holding the machine, the library and the page
// words (a page with <script src="s-web.js"> runs its <script type="text/s"> blocks), and
// s-core.js, the part of the machine a compiled page carries: no reader, no library text.
// With esbuild installed (npm i), both are also written minified (.min.js).
import fs from 'node:fs'
import { cut } from './parts.mjs'
const dir = new URL('.', import.meta.url).pathname
const read = (f) => fs.readFileSync(dir + f, 'utf8')
const strip = (t) => t.replace(/^import .*$/gm, '').replace(/^export (const|function|class|async function)/gm, '$1')
let esbuild = null
try { esbuild = await import('esbuild') } catch {}
const min = async (code) => esbuild ? (await esbuild.transform(code, { minify: true, target: 'es2020' })).code : null

const web = `// s-web.js — s for the page, generated by build.mjs from beads.js, s.js, std.js, dom.js, run.js
(function () {
${strip(read('beads.js'))}
${strip(read('s.js'))}
${strip(read('std.js'))}
${strip(read('dom.js'))}
${strip(read('run.js'))}
window.S = { Rt, runS, errorAt, LIB, parse, expand, mutualize, lineStats }
if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', () => autorun())
else autorun()
})()
`
// the machine without its reader: a compiled page has its code as functions already
const machine = strip(read('s.js')).replace(/\/\/ <reader>[^]*?\/\/ <\/reader>\n/, `function parse() { throw new Error('a compiled page has no reader') }\n`)
if (/function brace\(/.test(machine)) throw new Error('the reader is still in s-core.js')
const core = `// s-core.js — the machine a compiled s page carries, generated by build.mjs
var sCore = function () {
${machine}
${strip(read('dom.js'))}
return { Rt, attachDom, classify }
}
`
fs.writeFileSync(dir + 's-web.js', web)
fs.writeFileSync(dir + 's-core.js', core)
console.log('s-web.js', web.length, 'bytes; s-core.js', core.length, 'bytes')
const wm = await min(web), cm = await min(core)
if (wm) { fs.writeFileSync(dir + 's-web.min.js', wm); fs.writeFileSync(dir + 's-core.min.js', cm); console.log('minified', wm.length, cm.length) }

// the same machine in parts, for a compiled page to keep only what it reaches (shake.js)
if (esbuild) {
  // with the reader: a page whose code runs text it builds keeps it
  const src = `${strip(read('beads.js'))}\n${strip(read('s.js'))}\n${strip(read('dom.js'))}`
  const parts = await cut(src, async (code) => (await esbuild.transform(code, { minify: true, target: 'es2020' })).code)
  fs.writeFileSync(dir + 's-core.parts.json', JSON.stringify(parts))
  console.log('s-core.parts.json', parts.length, 'parts')
}
