# python3 studio/web/test/editor.py: the playground's editor in a browser: typing, zones,
# lanes, the middle button, the lane keys, mint view, undo, exports.
import functools, http.server, threading, sys, os
from playwright.sync_api import sync_playwright

STUDIO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
srv = http.server.ThreadingHTTPServer(('127.0.0.1', 0), functools.partial(http.server.SimpleHTTPRequestHandler, directory=STUDIO))
srv.RequestHandlerClass.log_message = lambda *a: None
threading.Thread(target=srv.serve_forever, daemon=True).start()
BASE = f'http://127.0.0.1:{srv.server_port}/web/'
ok = bad = 0
def eq(name, got, want):
    global ok, bad
    if got == want: ok += 1
    else:
        bad += 1
        print(f'--- {name}\n  want: {want!r}\n  got:  {got!r}')

with sync_playwright() as pw:
    b = pw.chromium.launch()
    ctx = b.new_context(viewport={'width': 1300, 'height': 850}, accept_downloads=True)
    pg = ctx.new_page()
    errs = []
    pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto(BASE + 'index.html')
    pg.wait_for_function("window.ed")
    pg.wait_for_timeout(400)
    pg.uncheck('#live')
    val = lambda: pg.evaluate('ed.value')
    caret = lambda: pg.evaluate('[ed.a, ed.b]')
    def setv(t, at=0):
        pg.evaluate('([t, at]) => { ed.value = t; ed.goTo(at) }', [t, at])
    def pos(x):  # the screen point of the caret position x
        return pg.evaluate('(x) => { const r = ed.caretRect(x), i = ed.inner.getBoundingClientRect(); return [r.cx + 1, r.cy] }', x)
    def go(x): pg.evaluate('(x) => ed.goTo(x)', x)

    # typing
    setv('')
    pg.keyboard.type('1 2 \\+ =~ >')
    eq('typing', val(), '1 2 \\+ =~ >')
    setv('')
    pg.keyboard.type('{')
    eq('a brace makes a zone', [val(), caret()], ['{}', [1, 1]])
    pg.keyboard.type('hi}')
    eq('typing the closing brace steps over it', [val(), caret()], ['{hi}', [4, 4]])
    pg.keyboard.type(' p')
    setv('{} x', 1)
    pg.keyboard.press('Backspace')
    eq('backspace takes an empty zone', val(), ' x')
    setv('ab cd', 0)
    pg.keyboard.press('Shift+End'); pg.keyboard.type('{')
    eq('a brace wraps the selection', val(), '{ab cd}')
    # crossing zone edges one position at a time
    setv('{a} p', 0)
    seen = []
    for _ in range(5):
        pg.keyboard.press('ArrowRight'); seen.append(caret()[1])
    eq('right steps over the edges', seen, [1, 2, 3, 4, 5])
    # clicking puts the caret where the pointer is
    setv('{alpha beta} p\n1 2 3 >', 0)
    x, y = pos(8); pg.mouse.click(x - 1, y)
    eq('click inside a zone', caret()[1], 8)
    x, y = pos(17); pg.mouse.click(x - 1, y)
    eq('click on the second line', caret()[1], 17)
    # lanes: up and down move between lanes
    setv('⟪111¦222¦333⟫ 10 \\+ =~ ⨝', 2)
    pg.keyboard.press('ArrowDown')
    eq('down to the next lane', caret()[1], 6)
    pg.keyboard.press('ArrowDown')
    eq('down to the last lane', caret()[1], 10)
    pg.keyboard.press('ArrowUp'); pg.keyboard.press('ArrowUp')
    eq('back up', caret()[1], 2)
    eq('lane rows drawn', pg.evaluate("document.querySelectorAll('.fork .lane').length"), 3)
    eq('faint copies of the shared beads', pg.evaluate("document.querySelectorAll('.fork .clone').length"), 2)
    eq('a fork in the page says nothing of how it runs', pg.evaluate("document.querySelector('.fork').dataset.how || null"), None)
    # lane keys
    setv('1 2', 0)
    pg.keyboard.press('Shift+ArrowRight')
    pg.keyboard.press('Control+Backslash')
    eq('Ctrl+\\ splits the selection', [val(), caret()[1]], ['⟪1¦⟫ 2', 3])
    pg.keyboard.type('5')
    pg.keyboard.press('Alt+Enter'); pg.keyboard.type('9')
    eq('Alt+Enter adds a lane', val(), '⟪1¦5¦9⟫ 2')
    pg.keyboard.press('Alt+Backspace')
    eq('Alt+Backspace removes it', val(), '⟪1¦5⟫ 2')
    pg.keyboard.press('End'); pg.keyboard.press('Control+Shift+BracketRight')
    eq('Ctrl+Shift+] joins', val(), '⟪1¦5⟫ 2⨝')
    go(2); pg.keyboard.press('Control+l'); pg.keyboard.type('n')
    eq('Ctrl+L labels the fork', val(), '⟪n:1¦5⟫ 2⨝')
    setv('the cat sat on the mat\nthe dog sat on the log', 0)
    pg.keyboard.press('Control+a'); pg.keyboard.press('Control+m')
    eq('Ctrl+M folds lines into one', val(), 'the ⟪cat¦dog⟫ sat on the ⟪mat¦log⟫')
    pg.keyboard.press('F6')
    eq('F6 shows the minted lines', pg.evaluate("[...document.querySelectorAll('.ed-mint .row')].map(d => d.value)"), ['the cat sat on the mat', 'the dog sat on the log'])
    pg.keyboard.press('Escape')
    eq('Escape closes mint view', pg.evaluate("document.querySelector('.ed-mint').hidden"), True)
    eq('status counts lanes', 'mints 2' in pg.inner_text('#where'), True)
    # undo and redo
    pg.keyboard.press('Control+z')
    eq('undo', val(), 'the cat sat on the mat\nthe dog sat on the log')
    pg.keyboard.press('Control+Shift+z')
    eq('redo', val(), 'the ⟪cat¦dog⟫ sat on the ⟪mat¦log⟫')
    # the middle button: a pointer, the wheel picks what, release wraps
    setv('1 >\n2 >', 0)
    x0, y0 = pos(0); x1, y1 = pos(3)
    pg.mouse.move(x0 + 1, y0); pg.mouse.down(button='middle')
    pg.mouse.move(x1 - 2, y1, steps=4)
    eq('the pointer shows the length and what', pg.evaluate("document.querySelector('.ptr.tag').textContent"), 'try · 3 chars · wheel for another')
    pg.mouse.up(button='middle')
    eq('middle-drag makes a try zone', val(), '{1 >} {err~ >} try\n2 >')
    eq('a red zone', pg.evaluate("document.querySelectorAll('.zone.z-try').length"), 1)
    setv('1 >\n2 >', 0)
    x0, y0 = pos(4); x1, y1 = pos(7)
    pg.mouse.move(x0 + 1, y0); pg.mouse.down(button='middle')
    pg.mouse.move(x1 - 2, y1, steps=4)
    pg.mouse.wheel(0, 100)
    eq('the wheel picks another', pg.evaluate("document.querySelector('.ptr.tag').textContent").split(' · ')[0], 'element')
    pg.mouse.up(button='middle')
    eq('middle-drag makes an element zone', [val(), pg.evaluate('ed.selected()')], ['1 >\n{2 >} div', 'div'])
    pg.mouse.wheel(0, -100)  # back to try for the next one
    # snapping: a drag that cuts a zone takes all of it
    setv('a {b c} d', 0)
    x0, y0 = pos(0); x1, y1 = pos(4)
    pg.mouse.move(x0 + 1, y0); pg.mouse.down(button='middle'); pg.mouse.move(x1, y1, steps=3)
    eq('the range grows to whole zones', pg.evaluate('ed.drag.range'), [0, 7])
    pg.keyboard.press('Escape'); pg.mouse.up(button='middle')
    # middle click on a zone: unwrap
    setv('{x y} p', 0)
    x, y = pos(2)
    pg.mouse.click(x, y, button='middle')
    pg.click('.ed-menu >> text=unwrap')
    eq('unwrap', val(), 'x y')
    setv('{x y} p', 0)
    x, y = pos(2)
    pg.mouse.click(x, y, button='middle')
    pg.click('.ed-menu >> text=make it try')
    eq('retype', val(), '{x y} {err~ >} try')
    # braces shown
    pg.check('#braces')
    eq('braces shown', pg.evaluate("getComputedStyle(document.querySelector('.edge.brace')).color") != 'rgba(0, 0, 0, 0)', True)
    pg.uncheck('#braces')
    # copy and paste
    setv('copy me', 0)
    pg.keyboard.press('Control+a'); pg.keyboard.press('Control+c'); pg.wait_for_timeout(100); pg.keyboard.press('End'); pg.keyboard.press('Control+v'); pg.wait_for_timeout(100)
    eq('copy and paste', val(), 'copy mecopy me')
    # errors: the place is marked and the status goes there
    setv('1 >\nnope.', 0)
    pg.click('#run')
    pg.wait_for_function("document.querySelector('#status').className == 'err'")
    eq('error box', pg.evaluate("document.querySelectorAll('.errbox').length") > 0, True)
    pg.click('#status')
    eq('status goes to the error', caret()[1], 4)
    # join results come back from the run
    setv('⟪1¦2⟫ 10 \\+ =~ ⨝ collect >', 0)
    pg.click('#run')
    pg.wait_for_selector('.joinres')
    eq('lanes at the join', pg.inner_text('.joinres'), '11  ¦  12')
    # mint view takes edits (BEADS §4.4)
    setv('⟪a¦b⟫ x y', 9)
    pg.keyboard.press('F6')
    rows = lambda: pg.evaluate("[...document.querySelectorAll('.ed-mint .row')].map(r => r.value)")
    row = lambda i: pg.locator('.ed-mint .row').nth(i)
    eq('the minted lines', rows(), ['a x y', 'b x y'])
    row(0).fill('a z y')
    eq('an edit in a shared bead changes every line', [val(), rows()], ['⟪a¦b⟫ z y', ['a z y', 'b z y']])
    row(1).fill('bb z y')
    eq('an edit in a lane changes the lines through it', [val(), rows()], ['⟪a¦bb⟫ z y', ['a z y', 'bb z y']])
    row(1).press('End'); pg.keyboard.type('w')
    eq('typing in a row', [val(), rows()], ['⟪a¦bb⟫ z yw', ['a z yw', 'bb z yw']])
    eq('the row keeps the caret', pg.evaluate("[document.activeElement.className, document.activeElement.selectionStart]"), ['row', 7])
    pg.check('.ed-mint .only')
    row(0).fill('a z q')
    eq('this line only: the bead splits into a fork', [val(), rows()], ['⟪a¦bb⟫ z ⟪q¦yw⟫', ['a z q', 'bb z yw']])
    setv('⟪a¦b⟫ ⨝ x ⟪c¦d⟫ ⨝', 0)
    pg.evaluate('ed.showMint()')
    row(2).fill('b x e')
    eq('this line only, where no fork zips: the line is mutualized', pg.evaluate("ed.value"), '⟪a¦a¦b¦b⟫ x ⟪c¦d¦e¦d⟫')
    eq('it mints what the rows say', [r.strip() for r in rows()], ['a x c', 'a x d', 'b x e', 'b x d'])
    pg.uncheck('.ed-mint .only')
    row(0).press('Escape')
    eq('Escape closes the mint view', pg.evaluate("document.querySelector('.ed-mint').hidden"), True)
    # commands where names belong
    setv('5 r n\n7 w l\n5 \\r n\nr >', 0)
    eq('a command word where a name belongs is marked', pg.evaluate("[...document.querySelectorAll('.k-clash')].map(s => s.textContent)"), ['r', 'w'])
    eq('the note names the escape', pg.evaluate("document.querySelector('.k-clash').title"), 'r runs the r command here, before n takes its name; {r} is the name r (\\r runs the command too)')
    # zones without colour: each kind has its own edge
    setv('{a} div {b} onclick {c} {d} try items {e} each {f} home page {g} x ><', 0)
    shape = pg.evaluate("""Object.fromEntries([...document.querySelectorAll('.zone')].map(z => {
      const e = getComputedStyle(z.querySelector('.edge.brace'))
      return [z.className.split(' ')[1], [e.borderRadius, e.borderLeftStyle, e.backgroundImage.split('(')[0], e.height, e.clipPath.split('(')[0], e.width]]
    }))""")
    eq('element square', shape['z-el'][0], '0px')
    eq('event round', shape['z-ev'][0], '50%')
    eq('try double', shape['z-try'][1], 'double')
    eq('loop dashed', shape['z-loop'][2], 'repeating-linear-gradient')
    eq('page tall', float(shape['z-page'][3][:-2]) > float(shape['z-el'][3][:-2]) * 1.4, True)
    eq('every kind its own edge', len(set(map(tuple, shape.values()))), len(shape))
    pg.check('#braces')
    eq('the braces toggle shows braces in every kind', pg.evaluate("[...document.querySelectorAll('.zone > .edge.brace')].every(e => getComputedStyle(e).color != 'rgba(0, 0, 0, 0)' && e.getBoundingClientRect().width > 4)"), True)
    pg.uncheck('#braces')
    # exports
    setv(open(os.path.join(STUDIO, 'web/examples/first.s')).read(), 0)
    with pg.expect_download() as d: pg.click('#export')
    html = open(d.value.path()).read()
    eq('compiled export has no script', '<script' in html, False)
    with pg.expect_download() as d: pg.click('#exportReader')
    eq('reader export carries the machine', 'function parse' in open(d.value.path()).read() or 'brace' in open(d.value.path()).read(), True)
    with pg.expect_download() as d: pg.click('#s5')
    eq('.s5 download', d.value.suggested_filename.endswith('.s5'), True)
    eq('no page errors', errs, [])
    b.close()
print(f'{ok} pass, {bad} fail')
sys.exit(1 if bad else 0)
